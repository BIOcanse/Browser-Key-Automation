import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const workspaceRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const registry = JSON.parse(await readFile(path.join(workspaceRoot, "registries", "ui.registry.json"), "utf8"));
const freedom = JSON.parse(await readFile(path.join(workspaceRoot, "registries", "freedom.registry.json"), "utf8"));

if (registry.registryId !== "ui.v1" || registry.schemaVersion !== 1 || !Array.isArray(registry.locales) || registry.locales.length !== 20) {
  throw new Error("UI registry must contain exactly 20 locales");
}
const localeTags = registry.locales.map((locale) => locale.tag);
if (new Set(localeTags).size !== localeTags.length || localeTags[0] !== "en" || !localeTags.includes("zh-CN") || !localeTags.includes("zh-TW")) {
  throw new Error("UI locale tags must be unique and include en, zh-CN and zh-TW");
}
for (const locale of registry.locales) {
  if (typeof locale.tag !== "string" || !/^[a-z]{2}(?:-[A-Z]{2})?$/u.test(locale.tag) ||
      typeof locale.nativeName !== "string" || locale.nativeName.trim() === "" ||
      !["ltr", "rtl"].includes(locale.direction) || !Array.isArray(locale.browserAliases) || locale.browserAliases.length === 0 ||
      locale.browserAliases.some((alias) => typeof alias !== "string" || alias.trim() === "")) {
    throw new Error(`Invalid UI locale definition: ${String(locale.tag)}`);
  }
}
if (registry.locales.filter((locale) => locale.direction === "rtl").map((locale) => locale.tag).join(",") !== "ar") {
  throw new Error("The current 20-locale set declares only Arabic as RTL");
}
const base = registry.translations?.en;
if (typeof base !== "object" || base === null || Array.isArray(base)) throw new Error("Missing English UI messages");
const messageKeys = Object.keys(base).sort();
if (messageKeys.length === 0 || new Set(messageKeys).size !== messageKeys.length) throw new Error("English UI messages are empty or duplicated");
const placeholderSet = (text) => [...text.matchAll(/\{([a-z][A-Za-z0-9]*)\}/gu)].map((match) => match[1]).sort();
for (const tag of localeTags) {
  const messages = registry.translations?.[tag];
  if (typeof messages !== "object" || messages === null || Array.isArray(messages)) throw new Error(`Missing UI messages: ${tag}`);
  const keys = Object.keys(messages).sort();
  if (JSON.stringify(keys) !== JSON.stringify(messageKeys)) throw new Error(`UI message keys differ from English: ${tag}`);
  for (const key of messageKeys) {
    if (typeof messages[key] !== "string" || messages[key].trim() === "") throw new Error(`Empty UI message: ${tag}.${key}`);
    if (JSON.stringify(placeholderSet(messages[key])) !== JSON.stringify(placeholderSet(base[key]))) {
      throw new Error(`UI message placeholders differ from English: ${tag}.${key}`);
    }
  }
}
const knownMessageKeys = new Set(messageKeys);
for (const relativePath of [
  "apps/extension/static/admin/index.html",
  "apps/extension/static/admin/welcome.html",
  "apps/extension/static/demo/index.html",
]) {
  const html = await readFile(path.join(workspaceRoot, relativePath), "utf8");
  for (const match of html.matchAll(/\bdata-i18n(?:-title|-aria|-placeholder)?="([^"]+)"/gu)) {
    if (!knownMessageKeys.has(match[1])) throw new Error(`Unknown UI message in ${relativePath}: ${match[1]}`);
  }
}
const defaultPoint = freedom.points.find((point) => point.pointId === "ui.locale.default");
const allowedPreferences = ["auto", ...localeTags];
if (defaultPoint?.status !== "active" || defaultPoint.kind !== "string" ||
    JSON.stringify(defaultPoint.allowedStrings) !== JSON.stringify(allowedPreferences) ||
    !allowedPreferences.includes(defaultPoint.defaultString)) throw new Error("ui.locale.default does not match the UI locale registry");

const generated = `// Generated by tools/generate-ui-config.mjs. Do not edit.\n` +
  `export const UI_DEFAULT_LOCALE = ${JSON.stringify(defaultPoint.defaultString)} as const;\n` +
  `export const UI_LOCALES = ${JSON.stringify(registry.locales, null, 2)} as const;\n` +
  `export const UI_MESSAGE_KEYS = ${JSON.stringify(messageKeys)} as const;\n` +
  `export type UiLocale = typeof UI_LOCALES[number]["tag"];\n` +
  `export type UiLocalePreference = typeof UI_DEFAULT_LOCALE | UiLocale;\n` +
  `export type UiMessageKey = typeof UI_MESSAGE_KEYS[number];\n` +
  `type UiMessageTable = { readonly [Key in UiMessageKey]: string };\n` +
  `export const UI_MESSAGES: Readonly<Record<UiLocale, UiMessageTable>> = ${JSON.stringify(registry.translations, null, 2)};\n`;
await writeFile(path.join(workspaceRoot, "apps", "extension", "src", "generated", "ui-config.ts"), generated);

export async function writeChromeLocales(outputRoot) {
  const resolvedOutput = path.resolve(outputRoot);
  const expectedParent = path.resolve(workspaceRoot, "out");
  if (path.relative(expectedParent, resolvedOutput).startsWith("..") || resolvedOutput === expectedParent) {
    throw new Error("Chrome locales may only be emitted into a build directory under out");
  }
  for (const locale of registry.locales) {
    const directory = path.join(resolvedOutput, "_locales", locale.tag.replaceAll("-", "_"));
    await mkdir(directory, { recursive: true });
    const messages = registry.translations[locale.tag];
    await writeFile(path.join(directory, "messages.json"), JSON.stringify({
      extensionDescription: { message: messages.extensionDescription },
      actionTitle: { message: messages.actionTitle },
    }, null, 2) + "\n");
  }
}
